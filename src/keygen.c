/* ==========================================================================
 * keygen.c - Key generation and derivation implementation
 * ==========================================================================
 *
 * Implements HMAC-SHA256 and a KDF to derive keys from seeds.
 *
 * HMAC-SHA256 follows RFC 2104:
 *   HMAC(key, msg) = SHA256((key XOR opad) || SHA256((key XOR ipad) || msg))
 *   where ipad = 0x36 repeated, opad = 0x5C repeated
 *
 * The KDF follows a simplified NIST SP 800-108 Counter Mode:
 *   derived = HMAC-SHA256(seed, label || 0x00 || "RoT-RISCV" || key_length)
 *
 * For the EK we use the label "ENDORSEMENT" and for the SRK "STORAGE",
 * matching the TPM 2.0 spec conventions.
 *
 * The seeds are hardcoded for now (simulating what would be burned into
 * hardware at manufacturing time). In a real device, these would come
 * from a hardware random number generator and be stored in one-time
 * programmable (OTP) memory.
 *
 * Author: Sebastian Alba
 * Project: Root of Trust Firmware for RISC-V with PMP isolation
 * ========================================================================== */

#include "keygen.h"
#include "secure_storage.h"
#include "uart.h"

/* -------------------------------------------------------------------------
 * Hardcoded seeds (simulating OTP/hardware provisioning)
 *
 * In a real device these would be generated by a true random number
 * generator at manufacturing time and burned into fuses or OTP memory.
 * They never leave the device and cannot be read back.
 *
 * We use two different seeds:
 *   - Endorsement seed: for the EK (device identity)
 *   - Storage seed: for the SRK (master key for storage hierarchy)
 *
 * These are different because the TPM spec says changing the owner
 * (which resets the SRK) should NOT change the device identity (EK).
 * ------------------------------------------------------------------------- */
static const uint8_t endorsement_seed[SEED_SIZE] = {
    0x7A, 0x1B, 0x3C, 0x4D, 0x5E, 0x6F, 0x80, 0x91,
    0xA2, 0xB3, 0xC4, 0xD5, 0xE6, 0xF7, 0x08, 0x19,
    0x2A, 0x3B, 0x4C, 0x5D, 0x6E, 0x7F, 0x90, 0xA1,
    0xB2, 0xC3, 0xD4, 0xE5, 0xF6, 0x07, 0x18, 0x29
};

static const uint8_t storage_seed[SEED_SIZE] = {
    0xF1, 0xE2, 0xD3, 0xC4, 0xB5, 0xA6, 0x97, 0x88,
    0x79, 0x6A, 0x5B, 0x4C, 0x3D, 0x2E, 0x1F, 0x00,
    0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88,
    0x99, 0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF, 0x10
};

/* -------------------------------------------------------------------------
 * hmac_sha256 - HMAC using SHA-256 (RFC 2104)
 *
 * HMAC works like this:
 *   1. If the key is longer than 64 bytes, hash it first
 *   2. Pad the key to 64 bytes
 *   3. XOR the padded key with 0x36 to make the inner key (ipad)
 *   4. XOR the padded key with 0x5C to make the outer key (opad)
 *   5. inner_hash = SHA256(ipad || message)
 *   6. result = SHA256(opad || inner_hash)
 *
 * This construction ensures that the MAC depends on both the key
 * and the message in a way that is secure against forgery.
 * ------------------------------------------------------------------------- */
void hmac_sha256(const uint8_t *key, uint32_t key_len,
                 const uint8_t *data, uint32_t data_len,
                 uint8_t output[SHA256_DIGEST_SIZE])
{
    uint8_t k_pad[SHA256_BLOCK_SIZE];
    uint8_t inner_hash[SHA256_DIGEST_SIZE];
    sha256_ctx ctx;
    uint32_t i;

    /* if key is too long, hash it first */
    if (key_len > SHA256_BLOCK_SIZE) {
        sha256(key, key_len, k_pad);
        for (i = SHA256_DIGEST_SIZE; i < SHA256_BLOCK_SIZE; i++) {
            k_pad[i] = 0;
        }
    } else {
        for (i = 0; i < key_len; i++) {
            k_pad[i] = key[i];
        }
        for (i = key_len; i < SHA256_BLOCK_SIZE; i++) {
            k_pad[i] = 0;
        }
    }

    /* inner hash: SHA256((key XOR ipad) || data) */
    sha256_init(&ctx);
    for (i = 0; i < SHA256_BLOCK_SIZE; i++) {
        k_pad[i] ^= 0x36;
    }
    sha256_update(&ctx, k_pad, SHA256_BLOCK_SIZE);
    sha256_update(&ctx, data, data_len);
    sha256_final(&ctx, inner_hash);

    /* restore k_pad (undo ipad, apply opad) */
    for (i = 0; i < SHA256_BLOCK_SIZE; i++) {
        k_pad[i] ^= 0x36 ^ 0x5C;
    }

    /* outer hash: SHA256((key XOR opad) || inner_hash) */
    sha256_init(&ctx);
    sha256_update(&ctx, k_pad, SHA256_BLOCK_SIZE);
    sha256_update(&ctx, inner_hash, SHA256_DIGEST_SIZE);
    sha256_final(&ctx, output);
}

/* -------------------------------------------------------------------------
 * kdf_derive - derive a key from seed and label
 *
 * Simplified KDF based on NIST SP 800-108 Counter Mode:
 *   output = HMAC-SHA256(seed, counter || label || 0x00 || context || bits)
 *
 * counter = 0x00000001 (we only need one block, 256 bits)
 * label = the string passed in (e.g. "ENDORSEMENT" or "STORAGE")
 * 0x00 = separator byte
 * context = "RoT-RISCV" (identifies our application)
 * bits = 0x00000100 (256 in big-endian, the output length in bits)
 * ------------------------------------------------------------------------- */
void kdf_derive(const uint8_t seed[SEED_SIZE],
                const char *label,
                uint8_t output[SHA256_DIGEST_SIZE])
{
    /*
     * Build the input buffer manually.
     * Max label length we support is 16 chars, that is plenty.
     * Total buffer: 4 (counter) + label_len + 1 (separator) + 9 (context) + 4 (bits)
     */
    uint8_t buf[48];
    uint32_t pos = 0;
    uint32_t i;

    /* counter = 1 (big-endian 32 bits) */
    buf[pos++] = 0x00;
    buf[pos++] = 0x00;
    buf[pos++] = 0x00;
    buf[pos++] = 0x01;

    /* label string */
    for (i = 0; label[i] != '\0' && i < 16; i++) {
        buf[pos++] = (uint8_t)label[i];
    }

    /* separator */
    buf[pos++] = 0x00;

    /* context: "RoT-RISCV" */
    buf[pos++] = 'R'; buf[pos++] = 'o'; buf[pos++] = 'T';
    buf[pos++] = '-';
    buf[pos++] = 'R'; buf[pos++] = 'I'; buf[pos++] = 'S';
    buf[pos++] = 'C'; buf[pos++] = 'V';

    /* output length in bits = 256 = 0x00000100 (big-endian) */
    buf[pos++] = 0x00;
    buf[pos++] = 0x00;
    buf[pos++] = 0x01;
    buf[pos++] = 0x00;

    hmac_sha256(seed, SEED_SIZE, buf, pos, output);
}

/* -------------------------------------------------------------------------
 * keygen_ek - generate Endorsement Key from endorsement seed
 * ------------------------------------------------------------------------- */
void keygen_ek(const uint8_t seed[SEED_SIZE],
               uint8_t ek[SHA256_DIGEST_SIZE])
{
    kdf_derive(seed, "ENDORSEMENT", ek);
}

/* -------------------------------------------------------------------------
 * keygen_srk - generate Storage Root Key from storage seed
 * ------------------------------------------------------------------------- */
void keygen_srk(const uint8_t seed[SEED_SIZE],
                uint8_t srk[SHA256_DIGEST_SIZE])
{
    kdf_derive(seed, "STORAGE", srk);
}

/* -------------------------------------------------------------------------
 * keygen_init - generate keys and store them in Secure Storage
 *
 * This runs once at boot. It derives the EK and SRK from their
 * respective seeds and stores them in the Secure Storage MMIO device.
 *
 * Because the seeds are fixed (simulating OTP), the same keys are
 * generated every boot. This gives the device a stable identity.
 * ------------------------------------------------------------------------- */
void keygen_init(void)
{
    uint8_t ek[SHA256_DIGEST_SIZE];
    uint8_t srk[SHA256_DIGEST_SIZE];
    uint32_t read_size;
    int i;

    if (ss_key_exists(KEY_ID_EK)) {
        uart_puts("[KEYGEN] EK found in Secure Storage (not first boot)\n");
        read_size = SHA256_DIGEST_SIZE;
        ss_read_key(KEY_ID_EK, ek, &read_size);
        uart_puts("[KEYGEN] EK loaded: ");
        for (i = 0; i < 8; i++) { uart_put_hex(ek[i]); uart_puts(" "); }
        uart_puts("...\n");
        read_size = SHA256_DIGEST_SIZE;
        ss_read_key(KEY_ID_SRK, srk, &read_size);
        uart_puts("[KEYGEN] SRK loaded: ");
        for (i = 0; i < 8; i++) { uart_put_hex(srk[i]); uart_puts(" "); }
        uart_puts("...\n");
        uart_puts("[KEYGEN] Keys restored from persistent storage\n");
        return;
    }

    uart_puts("[KEYGEN] First boot, deriving keys from seeds...\n");
    keygen_ek(endorsement_seed, ek);
    uart_puts("[KEYGEN] EK derived: ");
    for (i = 0; i < 8; i++) { uart_put_hex(ek[i]); uart_puts(" "); }
    uart_puts("...\n");
    keygen_srk(storage_seed, srk);
    uart_puts("[KEYGEN] SRK derived: ");
    for (i = 0; i < 8; i++) { uart_put_hex(srk[i]); uart_puts(" "); }
    uart_puts("...\n");
    ss_write_key(KEY_ID_EK, ek, SHA256_DIGEST_SIZE);
    ss_write_key(KEY_ID_SRK, srk, SHA256_DIGEST_SIZE);
    uart_puts("[KEYGEN] Keys stored in Secure Storage\n");
}
