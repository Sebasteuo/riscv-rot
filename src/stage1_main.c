#include <stdint.h>
#include "image.h"
#include "sha256.h"
#include "uart.h"
#include "tweetnacl.h"
#include "elf64.h"
#include "timer.h"

/*
 * Stage-1: the minimal trusted bootloader.
 *
 * It verifies an Ed25519 signature over the SHA-256 digest of the
 * Stage-2 payload before handing over control. If verification fails
 * it stops instead of booting.
 *
 * The public key below is embedded in .rodata. Unlike the golden hash
 * scheme it replaces, this value does not need to be protected against
 * modification: an attacker who swaps it still cannot produce a
 * signature that verifies, because that requires the private key, which
 * never enters the device. The security of the chain rests on Stage-1
 * being immutable, which on real hardware means mask ROM.
 */

#define STAGE2_IMAGE_ADDR  0x80200000UL

/* Ed25519 public key, generated by tools/sign_image.py */
static const uint8_t stage2_pubkey[32] = {
    PUBKEY_PLACEHOLDER
};

/* TweetNaCl needs this symbol but signature verification never calls it */
void randombytes(unsigned char *p, unsigned long long n)
{
    (void)p;
    (void)n;
}

static void halt(const char *why)
{
    uart_puts("[S1] HALT: ");
    uart_puts(why);
    uart_puts("\n[S1] Stage-2 was not started.\n");
    for (;;) {
        asm volatile("wfi");
    }
}

/*
 * crypto_sign_open() expects a signed message, that is signature
 * followed by message, and writes the recovered message out. The
 * message here is the 32-byte digest, so the buffers are small and
 * fixed size.
 */
static int verify_signature(const uint8_t *digest, const uint8_t *sig)
{
    uint8_t signed_msg[IMAGE_SIG_SIZE + 32];
    uint8_t recovered[IMAGE_SIG_SIZE + 32];
    unsigned long long recovered_len;
    int i;

    for (i = 0; i < IMAGE_SIG_SIZE; i++) {
        signed_msg[i] = sig[i];
    }
    for (i = 0; i < 32; i++) {
        signed_msg[IMAGE_SIG_SIZE + i] = digest[i];
    }

    return crypto_sign_open(recovered, &recovered_len,
                            signed_msg, sizeof(signed_msg),
                            stage2_pubkey);
}

uint64_t s1_hash_us;
uint64_t s1_sig_us;

static image_result_t verify_stage2(const image_header_t *hdr,
                                    const uint8_t *payload)
{
    uint8_t digest[32];
    uint64_t t0, t1, t2;

    if (hdr->magic != IMAGE_MAGIC) {
        return IMAGE_ERR_MAGIC;
    }

    /*
     * payload_size comes from the image and the image is untrusted at
     * this point. An oversized value would make the hash cover memory
     * outside the image, so it is bounded before any hashing happens.
     */
    if (hdr->payload_size == 0 ||
        hdr->payload_size > IMAGE_MAX_PAYLOAD) {
        return IMAGE_ERR_SIZE;
    }

    t0 = timer_now();
    sha256(payload, hdr->payload_size, digest);
    t1 = timer_now();

    if (verify_signature(digest, hdr->signature) != 0) {
        return IMAGE_ERR_SIGNATURE;
    }
    t2 = timer_now();

    s1_hash_us = (t1 - t0) / 10;
    s1_sig_us  = (t2 - t1) / 10;

    return IMAGE_OK;
}

void stage1_main(void)
{
    const image_header_t *hdr = (const image_header_t *)STAGE2_IMAGE_ADDR;
    const uint8_t *payload = (const uint8_t *)(STAGE2_IMAGE_ADDR +
                                               IMAGE_HEADER_SIZE);
    image_result_t result;
    elf_result_t load_rc;
    uint64_t entry = 0;
    void (*stage2_entry)(void);
    uint64_t t_start, t_verified, t_loaded;

    t_start = timer_now();
    uart_puts("\n[S1] Stage-1 bootloader\n");
    uart_puts("[S1] Verifying Stage-2 signature...\n");

    result = verify_stage2(hdr, payload);

    switch (result) {
    case IMAGE_ERR_MAGIC:
        halt("bad image magic");
        break;
    case IMAGE_ERR_SIZE:
        halt("payload size out of range");
        break;
    case IMAGE_ERR_SIGNATURE:
        halt("signature verification failed");
        break;
    case IMAGE_OK:
    default:
        break;
    }

    t_verified = timer_now();

    uart_puts("[S1] Signature valid, version ");
    uart_put_dec((uint64_t)hdr->version);
    uart_puts("\n[S1] Loading Stage-2 segments...\n");

    /*
     * Parsing happens only after the signature checks out, so the ELF
     * headers are authenticated before a single field is read.
     */
    load_rc = elf_load(payload, hdr->payload_size, &entry);
    if (load_rc != ELF_OK) {
        uart_puts("[S1] loader error code ");
        uart_put_dec((uint64_t)load_rc);
        uart_puts("\n");
        halt("Stage-2 image is malformed");
    }

    t_loaded = timer_now();

    /*
     * mtime runs at 10 MHz on the QEMU virt machine, so ticks divided
     * by 10 gives microseconds.
     */
    uart_puts("[S1] SHA-256 over payload: ");
    uart_put_dec(s1_hash_us);
    uart_puts(" us\n[S1] Ed25519 verify: ");
    uart_put_dec(s1_sig_us);
    uart_puts(" us\n[S1] Verification total: ");
    uart_put_dec((t_verified - t_start) / 10);
    uart_puts(" us\n[S1] Segment loading: ");
    uart_put_dec((t_loaded - t_verified) / 10);
    uart_puts(" us\n[S1] Stage-1 total: ");
    uart_put_dec((t_loaded - t_start) / 10);
    uart_puts(" us\n");

    uart_puts("[S1] Entry point ");
    uart_put_hex(entry);
    uart_puts("\n[S1] Transferring control\n\n");

    /* Make the freshly written instructions visible to the fetch unit */
    asm volatile("fence.i" ::: "memory");

    stage2_entry = (void (*)(void))entry;
    stage2_entry();

    halt("Stage-2 returned unexpectedly");
}
